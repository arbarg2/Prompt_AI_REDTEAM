"""Coverage matrix derived from the scenario registry plus explicitly unsupported areas."""
from __future__ import annotations

from .scenarios import CATEGORIES, REGISTRY

UNSUPPORTED = [
    ("pij", "Training-time data poisoning", "Requires access to model training; this target has no model."),
    ("sde", "True model inversion / membership inference", "No model; records are returned by rules, not inferred from weights."),
    ("sde", "Model-weight theft", "No model weights exist."),
    ("pij", "Real multimodal attacks (image/audio/video)", "Text-only API."),
    ("pij", "Model supply-chain compromise", "No model or dependency pipeline is under test."),
    ("res", "Real denial-of-service / infrastructure compromise", "Resource-abuse fixtures are bounded simulations; the target must never be stressed or used for DoS."),
    ("hcm", "Self-harm content", "Requests are refused by the engine guard; no surrogate is produced."),
    ("hcm", "Sexual content (including any involving minors)", "Requests are refused by the engine guard; nothing is generated."),
    ("hcm", "Real-detector-verified harmful content (violence, malware, hate, crime)", "Only an inert placeholder exists (hcm.surrogate); it cannot exercise a real detector."),
]
CATEGORY_ORDER = ["sde", "pij", "hcm", "res", "spd", "cmp"]


def matrix(enabled: frozenset[str] | None = None) -> list[dict]:
    rows = []
    for key in CATEGORY_ORDER:
        for s in sorted((x for x in REGISTRY.all() if x.category == key), key=lambda x: x.id):
            rows.append({"category": CATEGORIES[key], "category_key": key, "scenario_id": s.id, "scenario": s.name,
                         "implementation_status": s.status,
                         "behavior": {"implemented": "implemented", "simulated": "simulated", "placeholder": "placeholder"}[s.status],
                         "required_inputs": s.required_inputs, "profiles": list(s.profiles) if s.profiles else "all",
                         "expected_observable_outcome": s.outcome, "limitations": s.limitations,
                         **({"enabled": s.id in enabled} if enabled is not None else {})})
        for k, name, why in UNSUPPORTED:
            if k == key:
                rows.append({"category": CATEGORIES[key], "category_key": key, "scenario_id": None, "scenario": name,
                             "implementation_status": "unsupported", "behavior": "unsupported", "required_inputs": "-",
                             "profiles": "-", "expected_observable_outcome": "None", "limitations": why})
    return rows


def render_markdown() -> str:
    out = ["# Coverage", "",
           "<!-- GENERATED by scripts/gen_docs.py from the scenario registry. Do not edit by hand. -->", "",
           "This is a lightweight deterministic mock target. It does not reproduce every AI vulnerability, is not an exhaustive "
           "OWASP/MITRE mapping, and does not guarantee any external scanner will classify its responses as successful attacks. "
           "Dataset volume (record count) is reported separately from scenario coverage: 1,000 records are still the same set of scenarios.", "",
           "Status legend: **implemented** = deterministic behavior in the app; **simulated** = in-process simulation of agent/tool/resource "
           "behavior with no real tool, network or resource access; **placeholder** = inert stand-in that does not exercise a real detector "
           "(not counted as verified detector coverage); **unsupported** = not covered.", ""]
    rows = matrix()
    counts = {st: sum(r["implementation_status"] == st for r in rows) for st in ("implemented", "simulated", "placeholder", "unsupported")}
    out += [f"Totals: {counts['implemented']} implemented, {counts['simulated']} simulated, {counts['placeholder']} placeholder, "
            f"{counts['unsupported']} unsupported.", ""]
    for key in CATEGORY_ORDER:
        out += [f"## {CATEGORIES[key]}", "",
                "| ID | Scenario | Status | Required inputs | Expected observable outcome | Known limitations |", "|---|---|---|---|---|---|"]
        for r in (x for x in rows if x["category_key"] == key):
            out.append(f"| {('`' + r['scenario_id'] + '`') if r['scenario_id'] else '-'} | {r['scenario']} | {r['implementation_status']} | "
                       f"{r['required_inputs']} | {r['expected_observable_outcome']} | {r['limitations']} |")
        out.append("")
    out += ["## Precedence", "",
            "One scenario answers each prompt: a safety guard runs first (minor-related sexual content and self-harm are refused), then enabled "
            "scenarios in ascending priority order (first match wins; multi-turn escalation first, encoded/obfuscated variants last), then a benign "
            "fallback. Prompts that match nothing receive an ordinary answer with no leakage.", ""]
    return "\n".join(out)
